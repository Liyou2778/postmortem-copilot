# A deliberately small Markdown subset renderer.
#
# Why not the `markdown` package: our report format is fixed and generated by us
# (h1/h2, bold, inline code, bullet lists, pipe tables). Pulling a dependency for
# that adds install risk on a locked-down server for zero capability gain — and
# the install actually hung on a slow network during deployment.
_BOLD = re.compile(r"\*\*(.+?)\*\*")
_CODE = re.compile(r"`([^`]+)`")
_SEP = re.compile(r"^\|[\s:|-]+\|$")
# Evidence ids look like E-TLM-001 / E-CHG-002. Anchoring on the shapes we
# generate keeps the regex from matching arbitrary uppercase tokens.
_EV_ID = re.compile(r"\bE-[A-Z]{3}-\d{3}\b")


def _inline(text: str, task_id: str | None = None) -> str:
    """Escape first, then re-introduce the inline tags we support."""
    out = html.escape(text)
    out = _CODE.sub(r"<code>\1</code>", out)
    out = _BOLD.sub(r"<strong>\1</strong>", out)
    if task_id:
        # re.sub does not rescan its own replacement, so this cannot double-wrap.
        out = _EV_ID.sub(
            lambda m: (
                f'<a class="ev" href="/tasks/{task_id}/evidence/{m.group(0)}">{m.group(0)}</a>'
            ),
            out,
        )
    return out


def _split_row(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def md_to_html(text: str, task_id: str | None = None) -> str:
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if not stripped:
            i += 1
            continue

        # pipe table
        if stripped.startswith("|") and i + 1 < len(lines) and _SEP.match(lines[i + 1].strip()):
            header = _split_row(lines[i])
            i += 2
            body: list[list[str]] = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                body.append(_split_row(lines[i]))
                i += 1
            out.append("<table><thead><tr>")
            out.extend(f"<th>{_inline(c, task_id)}</th>" for c in header)
            out.append("</tr></thead><tbody>")
            for row in body:
                out.append("<tr>")
                out.extend(f"<td>{_inline(c, task_id)}</td>" for c in row)
                out.append("</tr>")
            out.append("</tbody></table>")
            continue

        if stripped.startswith("### "):
            out.append(f"<h3>{_inline(stripped[4:], task_id)}</h3>")
        elif stripped.startswith("## "):
            out.append(f"<h2>{_inline(stripped[3:], task_id)}</h2>")
        elif stripped.startswith("# "):
            out.append(f"<h1>{_inline(stripped[2:], task_id)}</h1>")
        elif stripped.startswith("- "):
            out.append("<ul>")
            while i < len(lines) and lines[i].strip().startswith("- "):
                out.append(f"<li>{_inline(lines[i].strip()[2:], task_id)}</li>")
                i += 1
            out.append("</ul>")
            continue
        else:
            out.append(f"<p>{_inline(stripped, task_id)}</p>")
        i += 1
    return "\n".join(out)

