def _flash(message: str = "", error: str = "") -> str:
    if error:
        return f'<div class="errbox">操作失败：{html.escape(error)}</div>'
    if message:
        return f'<div class="okbox">{html.escape(message)}</div>'
    return ""


def _mode_badge(mode: str) -> str:
    mode = mode if mode in ("real", "mock") else "real"
    return f'<span class="badge {mode}">{MODE_LABELS.get(mode, mode)}</span>'


