        f'关系: <strong>{quality.get("relations", 0)}</strong>　'
        f'无主: <strong>{quality.get("unowned", 0)}</strong>　'
        f'未接服务: <strong>{quality.get("unattached", 0)}</strong>　'
        f'缺 tier: <strong>{quality.get("missing_tier", 0)}</strong>　'
