def _inject_csrf(body: str) -> str:
    token = _CSRF_TOKEN.get()
    if not token:
        return body
    hidden = (
        '<input type="hidden" name="csrf_token" value="'
        f'{html.escape(token)}">'
    )

    def repl(match: re.Match[str]) -> str:
        tag = match.group(0)
        if "csrf_token" in tag:
            return tag
        return tag + hidden

    return re.sub(
        r'(<form\b[^>]*method=["\']post["\'][^>]*>)',
        repl, body, flags=re.IGNORECASE,
    )


